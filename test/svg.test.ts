import test from 'node:test';
import assert from 'node:assert/strict';
import { EditorHarness } from './EditorHarness.js';

test('SVG round-trip preserves nested hierarchy, geometry, defaults, text, z-order and presentation', async () => {
  const h = new EditorHarness();
  await h.exec('init 400 300', 'create g scene', 'set scene fill gold', 'create g node in scene',
    'create rect r 1.5 -2 3 4 in node', 'create circle c 5 6 7 red in node',
    'create ellipse e 8 9 10 11 in scene', 'create line l 0 1 2 3 black in scene',
    'create text t 20 40 "你好 <A> & \\"B\\"" in scene', 'set c stroke-width 2', 'save full.svg');
  const before = h.snapshot(); assert.match(before, /&lt;A&gt; &amp;/); assert.ok(!before.includes('text="你好'));
  await h.exec('init', 'read full.svg'); assert.equal(h.snapshot(), before);
  assert.equal(h.context.session.document.require('t').textContent, '你好 <A> & "B"');
  assert.equal(h.attr('r', 'fill'), undefined); assert.deepEqual(h.ids('scene'), ['node', 'e', 'l', 't']);
});

test('missing ids are generated by type with a full-file reservation pass and warnings in preorder', () => {
  const h = new EditorHarness();
  const result = h.codec.decode('<svg width="400" height="300"><rect/><g><rect id="rect1"/><circle/><text>ok</text></g><rect id="rect3"/><rect/></svg>');
  assert.deepEqual(result.warnings, ['warning: assigned id rect2 to unnamed <rect>', 'warning: assigned id g1 to unnamed <g>',
    'warning: assigned id circle1 to unnamed <circle>', 'warning: assigned id text1 to unnamed <text>', 'warning: assigned id rect4 to unnamed <rect>']);
  assert.deepEqual(result.document.all().map(shape => shape.id), ['rect2', 'g1', 'rect1', 'circle1', 'text1', 'rect3', 'rect4']);
});

test('duplicate explicit ids, including a root id collision, fail instead of renaming', () => {
  const h = new EditorHarness();
  for (const source of ['<svg><rect id="r"/><g id="r"/></svg>', '<svg id="r"><rect id="r"/></svg>']) {
    assert.throws(() => h.codec.decode(source), /id already exists: r/);
  }
});

test('failed read with duplicate ids or unsupported tag does not replace the current document', async () => {
  const h = new EditorHarness(); await h.exec('init', 'create g existing'); const before = h.snapshot();
  h.files.seed('duplicate.svg', '<svg><g id="a"/><g id="a"/></svg>');
  h.files.seed('unknown.svg', '<svg><rect/><path id="p" d="M0 0"/></svg>');
  await h.error('read duplicate.svg', 'id already exists: a');
  await h.error('read unknown.svg', 'unknown shape type: path (is the plugin loaded?)');
  assert.equal(h.snapshot(), before); await h.exec('undo'); assert.deepEqual(h.ids(), []);
});

test('invalid XML, non-SVG roots, invalid namespaces, dimensions and nested leaf content are rejected', () => {
  const h = new EditorHarness();
  for (const source of ['', '<svg><g>', '<svg><rect></circle></svg>', '<html/>', '<svg xmlns="urn:wrong"/>',
    '<svg width="100%"/>', '<svg viewBox="0 0 -1 4"/>', '<svg><rect width="-1"/></svg>',
    '<svg><text><tspan>x</tspan></text></svg>', '<svg><x:g xmlns:x="urn:x"/></svg>',
    '<!DOCTYPE svg [<!ENTITY x "bad">]><svg/>', '<svg><text>&unknown;</text></svg>']) {
    assert.throws(() => h.codec.decode(source), Error, source);
  }
});

test('viewBox, namespaces, px dimensions, root styles, text metadata and numeric defaults survive read/save', () => {
  const h = new EditorHarness();
  const { document } = h.codec.decode('<s:svg xmlns:s="http://www.w3.org/2000/svg" width="400px" height="300px" viewBox="-10 -20 100 80" fill="red"><s:text id="t" font-size="18" text-anchor="middle">文字 &amp; test</s:text><s:rect id="r"/></s:svg>');
  assert.equal(document.width, 400); assert.equal(document.height, 300); assert.equal(document.attributes.get('viewBox'), '-10 -20 100 80');
  assert.equal(document.require('t').attributes.get('font-size'), '18'); assert.equal(document.require('r').attributes.get('width'), '0');
  const encoded = h.codec.encode(document); const restored = h.codec.decode(encoded).document;
  assert.equal(restored.require('t').textContent, '文字 & test'); assert.equal(restored.attributes.get('fill'), 'red');
  assert.equal(h.codec.decode('<svg viewBox="0 0 120 90"/>').document.width, 120);
  assert.equal(h.codec.decode('<svg/>').document.height, 150);
});

test('nested translate/uniform-scale transforms are normalized with correct composition and text/stroke metrics', () => {
  const h = new EditorHarness();
  const { document } = h.codec.decode('<svg width="400" height="300"><g id="outer" transform="translate(60,40)"><g id="inner" transform="translate(200,0) scale(0.8)"><rect id="r" width="120" height="60" stroke-width="2"/><text id="t" x="60" y="38" font-size="16">End</text></g></g></svg>');
  const rect = document.require('r').attributes; const text = document.require('t').attributes;
  assert.equal(rect.get('x'), '260'); assert.equal(rect.get('y'), '40'); assert.equal(rect.get('width'), '96');
  assert.equal(rect.get('stroke-width'), '1.6'); assert.equal(text.get('x'), '308'); assert.equal(text.get('font-size'), '12.8');
  assert.equal(document.require('inner').attributes.get('transform'), undefined);
  assert.equal(h.codec.encode(h.codec.decode(h.codec.encode(document)).document), h.codec.encode(document));
});

test('unsupported transforms and scaled CSS fail explicitly rather than silently changing rendering', () => {
  const h = new EditorHarness();
  for (const transform of ['rotate(30)', 'scale(2,3)', 'scale(-1)', 'matrix(1 0 0 1 0 0)', 'translate(1 2 3)']) {
    assert.throws(() => h.codec.decode(`<svg><rect transform="${transform}"/></svg>`));
  }
  assert.throws(() => h.codec.decode('<svg><g transform="scale(2)" style="font-size:18px"><text>x</text></g></svg>'), /scaled inline CSS/);
});

test('unregistered data-kind=box degrades to ordinary g and can be manipulated as a normal container', async () => {
  const h = new EditorHarness();
  h.files.seed('box.svg', '<svg><g id="scene"><g id="box" data-kind="box"><rect id="r" width="10" height="10"/><text id="t">X</text></g></g></svg>');
  await h.exec('read box.svg', 'move box 10 20', 'ungroup box');
  assert.deepEqual(h.ids('scene'), ['r', 't']); assert.equal(h.attr('r', 'x'), '10');
});

test('read warnings appear only on successful import and each shape remains addressable', async () => {
  const h = new EditorHarness(); h.files.seed('missing.svg', '<svg><rect/><circle/><g><text>x</text></g></svg>');
  const results = await h.exec('read missing.svg'); assert.equal(results.filter(line => line.startsWith('warning:')).length, 4);
  await h.exec('set rect1 fill red', 'move g1 1 2', 'delete circle1', 'undo'); assert.ok(h.context.session.document.find('circle1'));
});

test('an imported root SVG id stays reserved during subsequent create and group commands', async () => {
  const h = new EditorHarness(); h.files.seed('root.svg', '<svg id="reserved"><g id="g"/></svg>');
  await h.exec('read root.svg'); const before = h.snapshot();
  await h.error('create g reserved', 'id already exists: reserved');
  await h.error('group reserved g', 'id already exists: reserved');
  assert.equal(h.snapshot(), before);
});
